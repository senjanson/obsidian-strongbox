export type Lang = "en" | "zh";
const tables: Record<Lang, Record<string, string>> = { en, zh };
let forced: Lang | null = null;

/**
 * Obsidian's interface language. An explicit choice is stored in
 * localStorage; when there is none (e.g. the mobile apps following the
 * system language) Obsidian's i18next instance knows what it picked.
 */
function obsidianLanguage(): string {
  const w = window as unknown as { i18next?: { language?: unknown } };
  const api = obsidian as unknown as { getLanguage?: () => unknown };
  const candidates: Array<() => unknown> = [
    () => window.localStorage?.getItem("language"),
    () => w.i18next?.language,
    () => api.getLanguage?.(),
  ];
  for (const get of candidates) {
    try {
      const v = get();
      if (typeof v === "string" && v) return v;
    } catch {
      /* try the next source */
    }
  }
  return "en";
}

function detect(): Lang {
  return obsidianLanguage().toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** For tests: pin the language, or pass null to follow Obsidian again. */
export function setLanguage(lang: Lang | null): void {
  forced = lang;
}

export function currentLanguage(): Lang {
  return forced ?? detect();
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  return tIn(currentLanguage(), key, vars);
}

export function tIn(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const text = tables[lang][key] ?? tables.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** For tests: every key in both tables. */
export function allKeys(lang: Lang): string[] {
  return Object.keys(tables[lang]);
}
